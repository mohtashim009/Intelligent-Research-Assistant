// Tool for analyzing report structure
const analyzeReportTool = createTool({
  id: 'analyze-report',
  description: 'Analyzes the structure and content of a research report to understand sections, formatting, and content',
  inputSchema: z.object({
    reportContent: z.string().describe('The full markdown content of the report to analyze'),
  }),
  outputSchema: z.object({
    sections: z.array(z.string()).describe('List of main sections found in the report'),
    format: z.string().describe('Current format style detected (e.g., "markdown", "academic", "informal")'),
    wordCount: z.number().describe('Approximate word count'),
    hasReferences: z.boolean().describe('Whether the report includes references/citations'),
    structure: z.string().describe('Description of the report structure'),
  }),
  execute: async ({ context }) => {
    const { reportContent } = context;

    // Extract sections (markdown headers)
    const sectionRegex = /^#{1,3}\s+(.+)$/gm;
    const sections: string[] = [];
    let match;
    while ((match = sectionRegex.exec(reportContent)) !== null) {
      sections.push(match[1]);
    }

    // Detect format characteristics
    const hasIEEEFormat = /\[(\d+)\]/.test(reportContent) || /IEEE/i.test(reportContent);
    const hasAPAFormat = /\(\w+,\s*\d{4}\)/.test(reportContent) || /APA/i.test(reportContent);
    const hasReferences = /##?\s*(References|Bibliography|Citations)/i.test(reportContent);

    let format = 'markdown';
    if (hasIEEEFormat) format = 'IEEE-style';
    else if (hasAPAFormat) format = 'APA-style';
    else if (sections.some(s => /abstract|introduction|methodology|conclusion/i.test(s))) {
      format = 'academic';
    }

    // Word count (approximate)
    const wordCount = reportContent.split(/\s+/).length;

    // Structure description
    const structure = sections.length > 0
      ? `Report has ${sections.length} main sections: ${sections.slice(0, 5).join(', ')}${sections.length > 5 ? '...' : ''}`
      : 'Report structure is informal or unstructured';

    return {
      sections,
      format,
      wordCount,
      hasReferences,
      structure,
    };
  },
});

